"""Per-label AUROC at the last turn for the baseline AND each auditor, from a finished run.

The run report lists auditor AUROCs only. Both auditors include the demographics-only prior,
so a high auditor AUROC can come from age and sex alone. This script puts the baseline's own
AUROC next to them. It reads the committed outputs and changes nothing.

    python scripts/auroc_with_baseline.py --run results/expected --out docs/demo_auroc.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from hta.config import read_json, read_jsonl
from hta.metrics import per_label_auroc


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="results/expected")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rd = Path(args.run)
    cfg = read_json(rd / "config.resolved.json")
    L = [c["id"] for c in cfg["labels"]["conditions"]] + [m["id"] for m in cfg["labels"]["medication_classes"]]
    people = sorted(read_jsonl(rd / "profiles" / "target.jsonl"), key=lambda p: p["person_id"])
    reps = [read_json(rd / "per_person" / f"{p['person_id']}.json") for p in people]
    y = np.array([[r["labels"][k] for k in L] for r in reps])
    cols = {"baseline": np.array([r["baseline"]["probs"] for r in reps])}
    for s in ("unfiltered", "filtered"):
        for a in reps[0]["settings"][s]["auditors"]:
            cols[f"{a} ({s})"] = np.array([r["settings"][s]["auditors"][a]["probs"][-1] for r in reps])
    auc = {name: per_label_auroc(p, y, L) for name, p in cols.items()}
    # REUSE-IgnoreStart
    lines = [
        "<!--\nSPDX-FileCopyrightText: 2026 Ruixiang Tang\nSPDX-License-Identifier: CC0-1.0\n-->",
        # REUSE-IgnoreEnd
        "",
        f"# Per-label AUROC at the last turn, with the baseline ({rd})",
        "",
        "Generated by `scripts/auroc_with_baseline.py` from the committed run; nothing was rerun.",
        f"{len(people)} people, so each value rests on very few positives (column n+). Compare each",
        "auditor with the baseline column: the part above the baseline is what the text added.",
        "",
        "| Label | n+ | " + " | ".join(cols) + " |",
        "|---|---|" + "---|" * len(cols),
    ]
    for j, k in enumerate(L):
        vals = ["n/a" if auc[c][k] is None else f"{auc[c][k]:.2f}" for c in cols]
        lines.append(f"| {k} | {int(y[:, j].sum())} | " + " | ".join(vals) + " |")
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[8:]))


if __name__ == "__main__":
    main()
